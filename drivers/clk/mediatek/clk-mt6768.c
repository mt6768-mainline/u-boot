#define PLL(_id, _reg, _pwr_reg, _en_mask, _flags, _pcwbits,		\
	    _pcwibits, _pd_reg, _pd_shift, _pcw_reg, _pcw_shift,		\
	    _fmin, _fmax) {						\
		.id = _id,						\
		.reg = _reg,						\
		.pwr_reg = _pwr_reg,					\
		.en_mask = _en_mask,					\
		.rst_bar_mask = BIT(23),				\
		.flags = _flags,					\
		.fmin = _fmin,						\
		.fmax = _fmax,						\
		.pcwbits = _pcwbits,					\
		.pcwibits = _pcwibits,					\
		.pd_reg = _pd_reg,					\
		.pd_shift = _pd_shift,					\
		.pcw_reg = _pcw_reg,					\
		.pcw_shift = _pcw_shift,				\
	}

