static int mt6768_bias_set(struct udevice *dev, u32 pin, bool disable,
			   bool pullup, u32 val)
{
	int err;

	err = mtk_pinconf_bias_set_pu_pd(dev, pin, disable, pullup, val);
	if (err != -EINVAL)
		return err;

	err = mtk_pinconf_bias_set_pupd_r1_r0(dev, pin, disable, pullup, val);
	if (err != -EINVAL)
		return err;

	return 0;
}

